"""The page shell every site page shares: head, top bar (brand, breadcrumbs, repo link), footer, static assets."""

from __future__ import annotations

import functools
import html
import subprocess
from pathlib import Path
from typing import Any

from .assets import CSS, JS


def e(value: Any) -> str:
    """HTML-escape any value (``None`` → empty string)."""
    return html.escape("" if value is None else str(value), quote=True)


def write_static(out_dir: Path) -> Path:
    """Write the shared CSS and JS into out_dir/assets/ and return that folder."""
    assets = out_dir / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    (assets / "style.css").write_text(CSS.lstrip(), encoding="utf-8")
    (assets / "app.js").write_text(JS.lstrip(), encoding="utf-8")
    return assets



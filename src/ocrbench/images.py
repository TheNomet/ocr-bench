"""Build/push images with `crane` (no Docker daemon needed).

<name> : per self-hosted backend: mirror backends.<name>.source_image into <prefix>-vllm:mirror-<digest>,
         then add one layer with /opt/serve.sh (from backends.<name>.serve_args) as entrypoint
         -> <prefix>-vllm:<name>-sagemaker
bench : runner.base_image + a dependencies layer (uv.lock, hash-checked) + an ocrbench layer (plus the
        optional extra CA), both installed for linux/amd64 locally with uv -> <prefix>-bench:latest.
        Layers are reproducible tarballs, so unchanged inputs give unchanged layer digests.
"""

from __future__ import annotations

import gzip
import io
import json
import shlex
import shutil
import subprocess
import tarfile
import tempfile
from pathlib import Path

import boto3

from .config import ROOT, Config


def _crane() -> str:
    for c in (ROOT / ".tools" / "crane", shutil.which("crane")):
        if c and Path(c).exists():
            return str(c)
    raise SystemExit("crane not found — run `just tools`")


def _sh(*args: str, stdin: str | None = None) -> str:
    r = subprocess.run(args, input=stdin, text=True, capture_output=True)
    if r.returncode:
        raise SystemExit(f"{' '.join(args[:3])}... failed:\n{r.stderr[-2000:]}")
    return r.stdout.strip()


def login(cfg: Config) -> None:
    tok = boto3.client("ecr", region_name=cfg.region).get_authorization_token()["authorizationData"][0]
    import base64

    pw = base64.b64decode(tok["authorizationToken"]).decode().split(":", 1)[1]
    _sh(_crane(), "auth", "login", cfg.registry, "-u", "AWS", "--password-stdin", stdin=pw)


def layer_bytes(files: dict[str, tuple[bytes, int]]) -> bytes:
    """files: archive path -> (content, mode). A reproducible tar.gz: sorted entries, zero mtimes,
    root ownership, no gzip name/mtime — the same files always give the same layer digest."""
    buf = io.BytesIO()
    with (
        gzip.GzipFile(filename="", mode="wb", fileobj=buf, mtime=0) as gz,
        tarfile.open(fileobj=gz, mode="w", format=tarfile.USTAR_FORMAT) as tar,
    ):
        for name in sorted(files):
            data, mode = files[name]
            ti = tarfile.TarInfo(name)
            ti.size, ti.mode, ti.mtime = len(data), mode, 0
            ti.uid = ti.gid = 0
            ti.uname = ti.gname = ""
            tar.addfile(ti, io.BytesIO(data))
    return buf.getvalue()


def _layer(files: dict[str, tuple[bytes, int]]) -> Path:
    """Writes layer_bytes(files) to a temporary .tgz and returns its path."""
    out = Path(tempfile.mkdtemp()) / "layer.tgz"
    out.write_bytes(layer_bytes(files))
    return out


def _tree(root: Path, dest: str) -> dict[str, tuple[bytes, int]]:
    """Every file under `root` (minus __pycache__) as `dest/<relative path>`, mode 0644."""
    return {
        f"{dest}/{f.relative_to(root).as_posix()}": (f.read_bytes(), 0o644)
        for f in sorted(root.rglob("*"))
        if f.is_file() and "__pycache__" not in f.parts
    }


def serve_script(o: dict) -> str:
    args = " \\\n  ".join(shlex.quote(a) for a in o.get("serve_args") or [])
    return f"""#!/bin/bash
# Generated by ocrbench from backends.<name>.serve_args. SageMaker runs `<entrypoint> serve`;
# vLLM provides /ping and /invocations on :8080. Weights are mounted at /opt/ml/model.
set -euo pipefail
export HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 VLLM_NO_USAGE_STATS=1 DO_NOT_TRACK=1
nvidia-smi || true
exec vllm serve /opt/ml/model \\
  --served-model-name {shlex.quote(o["served_model_name"])} \\
  {args} \\
  --host 0.0.0.0 --port 8080
"""


def recorded(cfg: Config) -> dict:
    """.state/<prefix>/images.json: {"selfhosted": {name: {"image", "source_digest"}}, "bench_image", ...}.
    The file from before several self-hosted backends existed ("ocr_image") is read as backend "ocr"."""
    p = cfg.state_dir / "images.json"
    data = json.loads(p.read_text()) if p.exists() else {}
    if "ocr_image" in data:
        data.setdefault("selfhosted", {})["ocr"] = {
            "image": data.pop("ocr_image"),
            "source_digest": data.pop("ocr_source_digest", None),
        }
    return data


def _record(cfg: Config, selfhosted: dict | None = None, **refs: str) -> None:
    """Pinned image references (repo@sha256:...) in .state/<prefix>/images.json; Terraform deploys these."""
    data = recorded(cfg)
    data.update(refs)
    if selfhosted:
        data.setdefault("selfhosted", {}).update(selfhosted)
    (cfg.state_dir / "images.json").write_text(json.dumps(data, indent=1) + "\n")


def pinned(ref: str, digest: str) -> str:
    """`name[:tag][@digest]` -> `name@digest` (the tag, if any, is dropped)."""
    name = ref.split("@", 1)[0]
    last = name.rsplit("/", 1)[-1]
    if ":" in last:
        name = name[: name.rfind(":")]
    return f"{name}@{digest}"


def _exists(c: str, ref: str) -> bool:
    return subprocess.run([c, "digest", ref], capture_output=True).returncode == 0


def build_selfhosted(cfg: Config, name: str) -> None:
    """Mirror the source image *by digest* (a moved tag can't change what we deploy), then add serve.sh."""
    c, o = _crane(), cfg.backend(name)
    repo = f"{cfg.registry}/{cfg.selfhosted_repo}"
    platform = o.get("image_platform", "linux/amd64")
    login(cfg)
    src = o["source_image"]
    digest = src.split("@", 1)[1] if "@" in src else _sh(c, "digest", "--platform", platform, src)
    if "@" not in src:
        print(
            f"note: {src} is a tag; pin backends.{name}.source_image as {src.split(':')[0]}@{digest} for reproducible builds"
        )
    mirror = f"{repo}:mirror-{digest.split(':')[1][:12]}"
    legacy = f"{repo}:mirror"  # older builds kept one moving tag; reuse it if it holds the same image
    if _exists(c, mirror):
        print(f"source {digest} already mirrored as {mirror}")
    elif _exists(c, legacy) and _sh(c, "digest", "--platform", platform, legacy) == digest:
        _sh(c, "tag", legacy, mirror.rsplit(":", 1)[1])
        print(f"source {digest} already mirrored; tagged {mirror}")
    else:
        print(f"mirroring {src} ({digest}) -> {mirror} (streams through this machine)")
        _sh(c, "copy", "--platform", platform, pinned(src, digest), mirror)
    layer = _layer({"opt/serve.sh": (serve_script(o).encode(), 0o755)})
    tag = f"{repo}:{name}-sagemaker"
    _sh(c, "append", "-b", mirror, "-f", str(layer), "-t", f"{tag}-base")
    _sh(c, "mutate", f"{tag}-base", "--entrypoint", "/opt/serve.sh", "--cmd", "", "-t", tag)
    built = _sh(c, "digest", tag)
    _record(cfg, selfhosted={name: {"image": f"{repo}@{built}", "source_digest": digest}})
    print(f"pushed {repo}@{built}")


def _check_app_matches_source(installed: Path, source: Path) -> None:
    """Every module of the package as installed for the image is byte-identical to the working tree: the bench
    task must run the code that was just tested, not a cached build of an older state."""
    src = {
        p.relative_to(source): p.read_bytes() for p in source.rglob("*") if p.is_file() and "__pycache__" not in p.parts
    }
    got = {
        p.relative_to(installed): p.read_bytes()
        for p in installed.rglob("*")
        if p.is_file() and "__pycache__" not in p.parts
    }
    stale = sorted(str(k) for k in src if got.get(k) != src[k])
    if stale:
        raise SystemExit(
            f"bench image would carry stale code ({len(stale)} files differ, e.g. {stale[:3]}); not pushed"
        )


def build_bench(cfg: Config) -> None:
    c, r = _crane(), cfg["runner"]
    repo = f"{cfg.registry}/{cfg.bench_repo}"
    login(cfg)
    work = Path(tempfile.mkdtemp())
    deps_dir, app_dir = work / "deps", work / "app"
    print("installing ocrbench + locked deps for linux/amd64 (uv.lock, hash-checked)")
    req = work / "requirements.txt"
    req.write_text(_sh("uv", "export", "--frozen", "--no-dev", "--no-emit-project", "--project", str(ROOT)))
    target = ["--python-version", "3.12", "--python-platform", "x86_64-manylinux_2_28", "--quiet"]
    # Two layers: the dependencies (change only with uv.lock) and ocrbench itself, so a code change
    # pushes a small layer and the reproducible deps layer keeps its digest.
    _sh("uv", "pip", "install", "--target", str(deps_dir), *target, "--require-hashes", "-r", str(req))
    # --no-cache: uv otherwise reuses an earlier build of this local package, and the image would run old code.
    _sh("uv", "pip", "install", "--target", str(app_dir), *target, "--no-deps", "--no-cache", str(ROOT))
    _check_app_matches_source(app_dir / "ocrbench", ROOT / "src" / "ocrbench")
    deps = _tree(deps_dir, "opt/ocrbench")
    app = _tree(app_dir, "opt/ocrbench")
    env = ["PYTHONPATH=/opt/ocrbench"]
    if r.get("extra_ca_pem"):
        pem = Path(r["extra_ca_pem"]).expanduser().read_bytes()
        app["opt/ocrbench-ca/extra.pem"] = (pem, 0o644)
        env.append("OCRBENCH_EXTRA_CA=/opt/ocrbench-ca/extra.pem")
    deps_layer, app_layer = _layer(deps), _layer(app)
    print(
        f"layers: deps {deps_layer.stat().st_size / 1e6:.1f} MB ({len(deps)} files), "
        f"app {app_layer.stat().st_size / 1e6:.1f} MB ({len(app)} files)"
    )
    base = r["base_image"]
    base_digest = base.split("@", 1)[1] if "@" in base else _sh(c, "digest", "--platform", "linux/amd64", base)
    base_ref = pinned(base, base_digest)
    layers = ["-f", str(deps_layer), "-f", str(app_layer)]
    _sh(c, "append", "--platform", "linux/amd64", "-b", base_ref, *layers, "-t", f"{repo}:base")
    mut = [c, "mutate", f"{repo}:base", "-t", f"{repo}:latest", "--entrypoint", "python,-m,ocrbench.cli"]
    for e in env:
        mut += ["--env", e]
    _sh(*mut)
    built = _sh(c, "digest", f"{repo}:latest")
    _record(cfg, bench_image=f"{repo}@{built}", bench_base_digest=base_digest)
    print(f"pushed {repo}@{built}")
